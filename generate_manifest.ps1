# Script to generate image manifest for frontend
$imagesFolder = "images"
$outputFile = "js/image_manifest.js"

# Resolve absolute paths to avoid issues
$baseDir = Get-Location
$imagesPath = Join-Path $baseDir $imagesFolder
$outputPath = Join-Path $baseDir $outputFile

Write-Host "Scanning images in: $imagesPath"

# Find all image files
if (Test-Path $imagesPath) {
    $files = Get-ChildItem -Path $imagesPath -Recurse -Include *.jpg, *.jpeg, *.png, *.webp, *.gif | Sort-Object Name
} else {
    Write-Error "Images folder not found at $imagesPath"
    exit 1
}

# Start building the JS file content
$jsContent = @"
// Auto-generated by generate_manifest.ps1
// Do not edit manually. Run the script to update.

export const imageManifest = [
"@

foreach ($file in $files) {
    # Get relative path (e.g., "images/1.jpg")
    $relativePath = "images/" + $file.Name 
    
    # Add to JS array
    $jsContent += "    { path: '$relativePath', name: '$($file.Name)' },`n"
}

$jsContent += "];`n"

# Only write if we found files, but write empty array if none to avoid breaking app
if ($null -eq $files) {
    Write-Warning "No images found!"
}

# Write to file
$jsContent | Out-File -FilePath $outputPath -Encoding UTF8
Write-Host "Generated $outputPath with $(@($files).Count) images."
